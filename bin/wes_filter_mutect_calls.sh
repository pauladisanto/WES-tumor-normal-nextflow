#!/usr/bin/env bash

# Stop the script when:
# - a command fails (-e);
# - an undefined variable is used (-u);
# - any command within a pipeline fails (pipefail).
set -euo pipefail

# Positional arguments supplied by the Nextflow FILTER_MUTECT_CALLS module.
tumor="$1"          # Tumor sample identifier.
normal="$2"         # Matched-normal sample identifier.
reference="$3"      # GRCh38 reference FASTA.
vcf="$4"            # Unfiltered somatic VCF generated by Mutect2.
stats="$5"          # Mutect2 statistics file associated with the VCF.
priors="$6"         # Orientation-bias priors from LearnReadOrientationModel.
contamination="$7"  # Tumor contamination estimate.
segments="$8"       # Tumor segmentation table from CalculateContamination.

# Common prefix used for the tumor-normal output files.
prefix="${tumor}_vs_${normal}"

# Apply GATK's somatic filters to the candidate variants produced by Mutect2.
# The filtering model incorporates Mutect2 statistics, read-orientation
# artifacts, estimated contamination, and tumor allele-balance segments.
gatk --java-options '-Xmx6g' FilterMutectCalls \
    -R "$reference" \
    -V "$vcf" \
    --stats "$stats" \
    --ob-priors "$priors" \
    --contamination-table "$contamination" \
    --tumor-segmentation "$segments" \
    -O "${prefix}.filtered.vcf.gz"